import { CefrLevel } from "./academy";
import { StructuredLesson } from "./academy-lessons";

type CompactWord = [string, string, string, string, string, string]; // [word, pos, ipa, meaningEn, meaningAr, example]

interface CompactLessonSeed {
  id: string;
  level: CefrLevel;
  unitNumber: number;
  title: string;
  titleAr: string;
  durationMins: number;
  objective: string;
  objectiveAr: string;
  words: CompactWord[];
  dialogueContext: string;
  dialogue: [string, string, string][]; // [speaker, text, ar]
  readingTitle: string;
  paragraphs: string[];
  quizQuestion: string;
  quizOptions: string[];
  quizCorrect: number;
  focusSound: string;
  tipEn: string;
  tipAr: string;
  shadowSentence: string;
  missionEn: string;
  missionAr: string;
  keyPhrases: string[];
}

function hydrateLesson(s: CompactLessonSeed): StructuredLesson {
  return {
    id: s.id,
    level: s.level,
    unitNumber: s.unitNumber,
    title: s.title,
    titleAr: s.titleAr,
    durationMins: s.durationMins,
    objective: s.objective,
    objectiveAr: s.objectiveAr,
    sourceRef: `CEFR ${s.level} • Unit ${s.unitNumber}`,
    vocabulary: s.words.map((w, idx) => ({
      id: `${s.id}-w${idx + 1}`,
      word: w[0],
      level: s.level,
      pos: w[1],
      ipa: w[2],
      meaningEn: w[3],
      meaningAr: w[4],
      example: w[5],
    })),
    listening: {
      title: s.title,
      context: s.dialogueContext,
      lines: s.dialogue.map(([speaker, text, translationAr]) => ({
        speaker,
        text,
        translationAr,
      })),
    },
    reading: {
      title: s.readingTitle,
      paragraphs: s.paragraphs,
      quiz: [
        {
          question: s.quizQuestion,
          options: s.quizOptions,
          correctIndex: s.quizCorrect,
        },
      ],
    },
    pronunciation: {
      focusSound: s.focusSound,
      tipEn: s.tipEn,
      tipAr: s.tipAr,
      shadowSentence: s.shadowSentence,
    },
    speakingMission: {
      promptEn: s.missionEn,
      promptAr: s.missionAr,
      targetMinutes: 7,
      keyPhrases: s.keyPhrases,
    },
  };
}

